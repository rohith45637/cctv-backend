from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field, ConfigDict


class AIAgentInvestigationRequest(BaseModel):
    """
    Contract payload prepared by Backend for external AI Investigation Agent.
    Contains authoritative identifiers and bounds for analysis.
    """
    investigation_id: str = Field(..., description="Target investigation identifier")
    event_id: Optional[str] = Field(None, description="Primary triggering event ID")
    threat_id: Optional[str] = Field(None, description="Primary triggering threat ID")
    incident_id: Optional[str] = Field(None, description="Associated incident ID")
    camera_id: Optional[str] = Field(None, description="Relevant camera ID")
    zone_id: Optional[str] = Field(None, description="Relevant zone ID")
    evidence_ids: List[str] = Field(default_factory=list, description="Authoritative evidence references")
    memory_ids: List[str] = Field(default_factory=list, description="Context memory references")
    requested_action: str = Field(default="ANALYZE_INCIDENT", description="Action requested from AI Agent")
    schema_version: str = Field(default="1.0", description="Contract schema version")

    model_config = ConfigDict(from_attributes=True)


class AIAgentInvestigationResponse(BaseModel):
    """
    Untrusted external output submitted by AI Investigation Agent to Backend.
    Subject to strict authoritative validation prior to any internal state change.
    """
    investigation_id: str = Field(..., description="Target investigation identifier")
    analysis: str = Field(..., min_length=5, description="Summary analysis generated by agent")
    findings: Optional[str] = Field(None, description="Investigative hypothesis or timeline reconstruction")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Self-reported analysis confidence score")
    evidence_references: List[str] = Field(default_factory=list, description="Referenced evidence item IDs")
    recommended_actions: List[str] = Field(default_factory=list, description="Recommended operational responses")
    schema_version: str = Field(default="1.0", description="Contract schema version")

    model_config = ConfigDict(from_attributes=True)


class AIAgentValidationResult(BaseModel):
    """
    Authoritative Backend audit evaluation of an untrusted AI Agent response.
    """
    investigation_id: str
    is_valid: bool
    status: str = Field(..., description="Validation outcome: ACCEPTED, REJECTED, INSUFFICIENT_EVIDENCE")
    confidence: float
    validated_evidence_ids: List[str] = Field(default_factory=list)
    rejected_evidence_ids: List[str] = Field(default_factory=list)
    recommended_actions: List[str] = Field(default_factory=list)
    findings: Optional[str] = None
    notes: Optional[str] = None
    schema_version: str = "1.0"
